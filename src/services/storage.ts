import { SongProject } from '../types/songwriter';
import { INITIAL_DEMO_PROJECT } from '../data/presets';

const STORAGE_KEY = 'ai_khmer_songwriter_projects';
const ACTIVE_PROJECT_KEY = 'ai_khmer_songwriter_active_id';

export class StorageService {
  static getProjects(): SongProject[] {
    try {
      const data = localStorage.getItem(STORAGE_KEY);
      if (!data) {
        // Seed with the initial sample project
        const initial = [INITIAL_DEMO_PROJECT];
        localStorage.setItem(STORAGE_KEY, JSON.stringify(initial));
        return initial;
      }
      return JSON.parse(data);
    } catch (e) {
      console.error('Failed to load projects from localStorage:', e);
      return [INITIAL_DEMO_PROJECT];
    }
  }

  static saveProject(project: SongProject): void {
    try {
      const projects = this.getProjects();
      const existingIdx = projects.findIndex((p) => p.id === project.id);
      const updatedProject = {
        ...project,
        updatedAt: new Date().toISOString(),
      };

      if (existingIdx >= 0) {
        projects[existingIdx] = updatedProject;
      } else {
        projects.unshift(updatedProject);
      }

      localStorage.setItem(STORAGE_KEY, JSON.stringify(projects));
      localStorage.setItem(ACTIVE_PROJECT_KEY, project.id);
    } catch (e) {
      console.error('Failed to save project:', e);
    }
  }

  static deleteProject(id: string): SongProject[] {
    try {
      const projects = this.getProjects().filter((p) => p.id !== id);
      localStorage.setItem(STORAGE_KEY, JSON.stringify(projects));
      return projects;
    } catch (e) {
      console.error('Failed to delete project:', e);
      return [];
    }
  }

  static duplicateProject(id: string): SongProject | null {
    const projects = this.getProjects();
    const source = projects.find((p) => p.id === id);
    if (!source) return null;

    const duplicated: SongProject = {
      ...source,
      id: 'song_' + Date.now() + '_' + Math.random().toString(36).substring(2, 7),
      title: `${source.title} (Copy)`,
      titleKhmer: `${source.titleKhmer} (ចម្លង)`,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    this.saveProject(duplicated);
    return duplicated;
  }

  static getActiveProjectId(): string | null {
    return localStorage.getItem(ACTIVE_PROJECT_KEY);
  }

  static setActiveProjectId(id: string): void {
    localStorage.setItem(ACTIVE_PROJECT_KEY, id);
  }

  // Export utilities
  static exportAsText(project: SongProject): void {
    const content = `TITLE: ${project.titleKhmer || project.title}
GENRE: ${project.analysis?.genre || 'Khmer Song'}
TEMPO / ENERGY: ${project.analysis?.tempoEnergy || ''}
VOCALS: ${project.analysis?.vocalType || ''}

=== SUNO AI MUSIC STYLE PROMPT ===
${project.sunoPrompt?.styleOfMusic || ''}

=== SUNO AI EXCLUDE STYLES ===
${project.sunoPrompt?.negativeStyle || ''}

=== LYRICS ===
${project.lyrics || ''}

---
Created with AI Khmer Songwriter Pro`;

    this.downloadFile(content, `${project.title || 'khmer-song'}.txt`, 'text/plain;charset=utf-8');
  }

  static exportAsMarkdown(project: SongProject): void {
    const content = `# ${project.titleKhmer || project.title}
*English Title: ${project.analysis?.titleEnglish || project.title}*

- **Genre:** ${project.analysis?.genre || 'N/A'}
- **Emotion:** ${project.analysis?.emotion || 'N/A'}
- **Vocals:** ${project.analysis?.vocalType || 'N/A'}
- **Tempo:** ${project.analysis?.tempoEnergy || 'N/A'}
- **Duration:** ${project.analysis?.duration || 'N/A'}

## Suno AI Style Prompt
\`\`\`
${project.sunoPrompt?.styleOfMusic || ''}
\`\`\`

**Negative Style:** \`${project.sunoPrompt?.negativeStyle || ''}\`

## Lyrics
\`\`\`
${project.lyrics || ''}
\`\`\`

## Extended Studio Arrangement Notes
${project.sunoPrompt?.extendedStyle || ''}

---
*Generated by AI Khmer Songwriter Pro*
`;

    this.downloadFile(content, `${project.title || 'khmer-song'}.md`, 'text/markdown;charset=utf-8');
  }

  static exportAsJson(project: SongProject): void {
    const content = JSON.stringify(project, null, 2);
    this.downloadFile(content, `${project.title || 'khmer-song'}.json`, 'application/json');
  }

  private static downloadFile(content: string, filename: string, type: string) {
    const blob = new Blob([content], { type });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename.replace(/[/\\?%*:|"<>]/g, '-');
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }
}
