import React, { useState } from 'react';
import { 
  Sparkles, 
  Copy, 
  Check, 
  ExternalLink, 
  Info, 
  Layers, 
  Music4, 
  Ban, 
  FileText,
  FileCode2,
  CheckCheck
} from 'lucide-react';
import { SunoPrompt } from '../types/songwriter';
import { Language, TRANSLATIONS } from '../i18n/translations';

interface SunoPromptCardProps {
  sunoPrompt: SunoPrompt;
  onChange: (val: SunoPrompt) => void;
  lyrics: string;
  songTitle: string;
  language: Language;
}

export const SunoPromptCard: React.FC<SunoPromptCardProps> = ({
  sunoPrompt,
  onChange,
  lyrics,
  songTitle,
  language,
}) => {
  const [copiedField, setCopiedField] = useState<string | null>(null);
  const [copiedAll, setCopiedAll] = useState<boolean>(false);
  const t = TRANSLATIONS[language];

  const handleCopy = (text: string, fieldName: string) => {
    navigator.clipboard.writeText(text);
    setCopiedField(fieldName);
    setTimeout(() => setCopiedField(null), 2000);
  };

  const handleCopyAll = () => {
    const fullBundle = `=== SUNO AI SONG SPECIFICATION ===

[1. SONG TITLE]
${songTitle || sunoPrompt.title}

[2. STYLE OF MUSIC]
${sunoPrompt.styleOfMusic}

[3. EXCLUDE STYLES (NEGATIVE)]
${sunoPrompt.negativeStyle || 'None'}

[4. ADDITIONAL INSTRUCTIONS]
${sunoPrompt.additionalInstructions || 'None'}

[5. LYRICS]
${lyrics || sunoPrompt.lyrics}

===================================
Generated by AI Khmer Songwriter Pro`;

    navigator.clipboard.writeText(fullBundle);
    setCopiedAll(true);
    setTimeout(() => setCopiedAll(false), 2500);
  };

  return (
    <div className="flex flex-col gap-4 rounded-2xl border border-slate-800 bg-slate-900/60 p-4 sm:p-5 backdrop-blur-sm shadow-xl">
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-slate-800 pb-3">
        <div className="flex items-center gap-2">
          <div className="flex h-8 w-8 items-center justify-center rounded-xl bg-gradient-to-tr from-cyan-500 to-indigo-500 shadow-md shadow-cyan-500/20 text-white">
            <Music4 className="h-4 w-4" />
          </div>
          <div>
            <h3 className="text-sm sm:text-base font-bold text-white flex items-center gap-1.5">
              {t.sunoTitle}
            </h3>
            <p className="text-[11px] text-slate-400">
              {t.sunoDesc}
            </p>
          </div>
        </div>

        {/* Copy All & External Link */}
        <div className="flex items-center gap-2">
          <button
            onClick={handleCopyAll}
            className="flex items-center gap-1.5 rounded-xl bg-gradient-to-r from-cyan-600 to-purple-600 px-3.5 py-1.5 text-xs font-bold text-white shadow-md shadow-cyan-500/20 hover:from-cyan-500 hover:to-purple-500 transition active:scale-95 cursor-pointer"
          >
            {copiedAll ? (
              <>
                <CheckCheck className="h-3.5 w-3.5 text-emerald-300" />
                <span>{t.copied}</span>
              </>
            ) : (
              <>
                <Copy className="h-3.5 w-3.5" />
                <span>{t.copyAllSuno}</span>
              </>
            )}
          </button>

          <a
            href="https://suno.com/create"
            target="_blank"
            rel="noopener noreferrer"
            className="flex items-center gap-1 rounded-xl border border-slate-700 bg-slate-800/80 px-2.5 py-1.5 text-xs font-medium text-slate-300 hover:text-white hover:border-slate-600 transition"
            title="Open Suno AI Creator"
          >
            <span className="hidden sm:inline">Suno.com</span>
            <ExternalLink className="h-3 w-3 text-cyan-400" />
          </a>
        </div>
      </div>

      {/* Field 1: Song Title */}
      <div className="flex flex-col gap-1.5">
        <div className="flex items-center justify-between text-xs font-semibold text-slate-300">
          <span className="flex items-center gap-1.5">
            <span className="flex h-4 w-4 items-center justify-center rounded-full bg-purple-900/60 text-[10px] text-purple-300">1</span>
            {t.songTitle}
          </span>
          <button
            onClick={() => handleCopy(songTitle || sunoPrompt.title, 'title')}
            className="flex items-center gap-1 text-[11px] text-slate-400 hover:text-white transition"
          >
            {copiedField === 'title' ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
            <span>{copiedField === 'title' ? t.copied : 'Copy'}</span>
          </button>
        </div>
        <input
          type="text"
          value={sunoPrompt.title || songTitle}
          onChange={(e) => onChange({ ...sunoPrompt, title: e.target.value })}
          className="rounded-xl border border-slate-700 bg-slate-950/80 px-3 py-2 text-xs text-slate-100 focus:border-purple-500 focus:outline-none"
        />
      </div>

      {/* Field 2: Style of Music (Targeted for Suno character limit) */}
      <div className="flex flex-col gap-1.5">
        <div className="flex items-center justify-between text-xs font-semibold text-slate-300">
          <span className="flex items-center gap-1.5">
            <span className="flex h-4 w-4 items-center justify-center rounded-full bg-cyan-900/60 text-[10px] text-cyan-300">2</span>
            {t.styleOfMusic}
            <span className="text-[10px] font-normal text-slate-500">
              ({sunoPrompt.styleOfMusic?.length || 0}/120 chars)
            </span>
          </span>
          <button
            onClick={() => handleCopy(sunoPrompt.styleOfMusic, 'style')}
            className="flex items-center gap-1 text-[11px] text-slate-400 hover:text-white transition"
          >
            {copiedField === 'style' ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
            <span>{copiedField === 'style' ? t.copied : 'Copy'}</span>
          </button>
        </div>
        <textarea
          rows={2}
          value={sunoPrompt.styleOfMusic}
          onChange={(e) => onChange({ ...sunoPrompt, styleOfMusic: e.target.value })}
          placeholder="E.g. Sad Khmer acoustic ballad, emotional male vocal, piano, strings, 68 bpm"
          className="rounded-xl border border-slate-700 bg-slate-950/80 p-2.5 text-xs text-cyan-200 focus:border-cyan-500 focus:outline-none font-mono"
        />
      </div>

      {/* Field 3: Lyrics with Section Tags */}
      <div className="flex flex-col gap-1.5">
        <div className="flex items-center justify-between text-xs font-semibold text-slate-300">
          <span className="flex items-center gap-1.5">
            <span className="flex h-4 w-4 items-center justify-center rounded-full bg-indigo-900/60 text-[10px] text-indigo-300">3</span>
            {language === 'km' ? 'ទំនុកច្រៀងតាមទម្រង់ Suno (Lyrics with Tags)' : 'Lyrics with Tags'}
          </span>
          <button
            onClick={() => handleCopy(lyrics, 'lyrics')}
            className="flex items-center gap-1 text-[11px] text-slate-400 hover:text-white transition"
          >
            {copiedField === 'lyrics' ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
            <span>{copiedField === 'lyrics' ? t.copied : 'Copy'}</span>
          </button>
        </div>
        <div className="rounded-xl border border-slate-800 bg-slate-950/60 p-2.5 text-[11px] text-slate-300 font-sans max-h-36 overflow-y-auto whitespace-pre-wrap leading-relaxed">
          {lyrics || 'No lyrics generated yet. Click "Generate Lyrics" to generate.'}
        </div>
      </div>

      {/* Field 4: Exclude Styles / Negative Style */}
      <div className="flex flex-col gap-1.5">
        <div className="flex items-center justify-between text-xs font-semibold text-slate-300">
          <span className="flex items-center gap-1.5 text-rose-300">
            <Ban className="h-3.5 w-3.5" />
            {t.negativePrompt} (Negative Style)
          </span>
          <button
            onClick={() => handleCopy(sunoPrompt.negativeStyle, 'negative')}
            className="flex items-center gap-1 text-[11px] text-slate-400 hover:text-white transition"
          >
            {copiedField === 'negative' ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
            <span>{copiedField === 'negative' ? t.copied : 'Copy'}</span>
          </button>
        </div>
        <input
          type="text"
          value={sunoPrompt.negativeStyle}
          onChange={(e) => onChange({ ...sunoPrompt, negativeStyle: e.target.value })}
          placeholder="E.g. EDM, autotune, distortion, party, screaming"
          className="rounded-xl border border-slate-700 bg-slate-950/80 px-3 py-1.5 text-xs text-rose-200 focus:border-rose-500 focus:outline-none"
        />
      </div>

      {/* Field 5: Extended Studio Notes & Instructions */}
      <div className="flex flex-col gap-1.5">
        <div className="flex items-center justify-between text-xs font-semibold text-slate-300">
          <span className="flex items-center gap-1.5 text-indigo-300">
            <Info className="h-3.5 w-3.5" />
            {t.extendedNotes}
          </span>
          <button
            onClick={() => handleCopy(sunoPrompt.extendedStyle || sunoPrompt.additionalInstructions, 'extended')}
            className="flex items-center gap-1 text-[11px] text-slate-400 hover:text-white transition"
          >
            {copiedField === 'extended' ? <Check className="h-3 w-3 text-emerald-400" /> : <Copy className="h-3 w-3" />}
            <span>{copiedField === 'extended' ? t.copied : 'Copy'}</span>
          </button>
        </div>
        <div className="rounded-xl border border-slate-800 bg-slate-950/50 p-2.5 text-[11px] text-slate-400 leading-relaxed max-h-28 overflow-y-auto">
          {sunoPrompt.extendedStyle || sunoPrompt.additionalInstructions || 'Studio arrangement notes appear here.'}
        </div>
      </div>

      {/* Disclaimer Notice */}
      <div className="rounded-xl border border-cyan-500/20 bg-cyan-950/20 p-2.5 text-[11px] text-cyan-300/80 flex items-start gap-2">
        <Info className="h-4 w-4 shrink-0 text-cyan-400 mt-0.5" />
        <p>
          {language === 'km'
            ? 'ចំណាំ៖ កម្មវិធីនេះបង្កើត Prompt និងទំនុកច្រៀងយ៉ាងស៊ីជម្រៅ សម្រាប់យកទៅ Paste ក្នុង Suno AI (Custom Mode) ឬ Udio ដើម្បី Render បទចម្រៀងជាសំឡេងពិតប្រាកដ។'
            : 'Note: This app creates tailored prompts and lyrics for Suno AI (Custom Mode) & Udio to render real music tracks.'}
        </p>
      </div>
    </div>
  );
};
